/**
 * Gets the 2-letter ISO code for a country name.
 */
export const getCountryIso2 = (countryName) => {
  if (!countryName || typeof countryName !== 'string') return null;
  const clean = countryName.trim().toUpperCase();
  if (clean.length === 2) return clean.toLowerCase();
  if (COUNTRY_ISO2[clean]) return COUNTRY_ISO2[clean].toLowerCase();

  const matchKey = Object.keys(COUNTRY_ISO2).find(k => clean.startsWith(k) || k.startsWith(clean));
  if (matchKey) return COUNTRY_ISO2[matchKey].toLowerCase();

  return null;
};

/**
 * Gets the default currency code for a country.
 */
export const getCountryDefaultCurrency = (countryName) => {
  if (!countryName || typeof countryName !== 'string') return 'USD';
  const clean = countryName.trim().toUpperCase();
  if (COUNTRY_DEFAULT_CURRENCIES[clean]) {
    return COUNTRY_DEFAULT_CURRENCIES[clean];
  }

  const matchKey = Object.keys(COUNTRY_DEFAULT_CURRENCIES).find(k => clean.startsWith(k) || k.startsWith(clean));
  if (matchKey) {
    return COUNTRY_DEFAULT_CURRENCIES[matchKey];
  }

  return 'USD';
};


