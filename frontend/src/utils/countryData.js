/**
 * Gets the international dialing code for a country.
 */
export const getCountryCallingCode = (countryName) => {
  if (!countryName || typeof countryName !== 'string') return '+91';
  const clean = countryName.trim().toUpperCase();
  if (COUNTRY_CALLING_CODES[clean]) {
    return COUNTRY_CALLING_CODES[clean];
  }

  // Check startsWith
  const matchKey = Object.keys(COUNTRY_CALLING_CODES).find(k => clean.startsWith(k) || k.startsWith(clean));
  if (matchKey) {
    return COUNTRY_CALLING_CODES[matchKey];
  }

  return '+1'; // fallback
};

